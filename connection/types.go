// Package connection implements authenticated agents sessions and bounded flow
// admission over a caller-provided byte transport. TLS belongs to that transport.
package connection

import (
	"context"
	"errors"
	"time"
)

// ProtocolVersion 3 drops the approval revision and provider declarations from
// HELLO: Control-computed effective configuration, not the session, scopes flows.
const ProtocolVersion = 3

type Role string

const (
	RoleAccess   Role = "access"
	RoleProvider Role = "provider"
)

type Purpose string

const (
	// PurposeAccess carries an untrusted candidate destination to the Edge.
	PurposeAccess Purpose = "access"
	// PurposeServe and PurposeEgress are only opened by the Edge to a provider.
	PurposeServe  Purpose = "serve"
	PurposeEgress Purpose = "egress"
)

// Hello is untrusted until the server's Authenticate callback approves it.
type Hello struct {
	Version     int    `json:"version"`
	Role        Role   `json:"role"`
	Workspace   string `json:"workspace"`
	AgentID     string `json:"agent_id"`
	ConnectorID string `json:"connector_id,omitempty"`
	Generation  uint64 `json:"generation"`
	Token       string `json:"token"`
}

// Principal is the authoritative identity returned by Authenticate, never a
// direct copy of a peer's Hello. SessionID is generated by the server.
// PrincipalType/PrincipalID identify who the Agent runs as (a User or a Service
// Account); they are typed so a Service Account is never mistaken for a User.
type Principal struct {
	Role          Role      `json:"role"`
	Workspace     string    `json:"workspace"`
	AgentID       string    `json:"agent_id"`
	ConnectorID   string    `json:"connector_id,omitempty"`
	PrincipalType string    `json:"principal_type,omitempty"`
	PrincipalID   string    `json:"principal_id,omitempty"`
	Generation    uint64    `json:"generation"`
	SessionID     string    `json:"session_id"`
	ExpiresAt     time.Time `json:"expires_at"`
}

type Welcome struct {
	Version int `json:"version"`
	Principal
}

type Destination struct {
	Host string `json:"host"`
	Port uint16 `json:"port"`
}

// OpenRequest describes a logical stream, not an arbitrary transport dial.
// Serve identifies a configured Resource; Access carries a candidate TLS target.
// Revision records the effective configuration revision the opener decided on;
// receivers authorize by content, so a newer revision never invalidates a flow
// that is still permitted. Capability is an opaque extension point, with
// verification owned by the caller.
type OpenRequest struct {
	FlowID      string      `json:"flow_id"`
	Purpose     Purpose     `json:"purpose"`
	Resource    string      `json:"resource,omitempty"`
	Destination Destination `json:"destination,omitempty"`
	Protocol    string      `json:"protocol,omitempty"`
	Revision    uint64      `json:"revision"`
	Deadline    time.Time   `json:"deadline"`
	// LeaseExpiresAt is a short renewable authorization lease. Deadline remains
	// the immutable maximum lifetime; zero retains legacy fixed-deadline mode.
	LeaseExpiresAt time.Time `json:"lease_expires_at,omitempty"`
	Capability     string    `json:"capability,omitempty"`
}

// OpenClaims is the receiver's authorized view. Only an AuthorizeOpen callback
// may produce these claims. They do not assert a cryptographic capability exists.
type OpenClaims struct {
	FlowID         string      `json:"flow_id"`
	Purpose        Purpose     `json:"purpose"`
	Resource       string      `json:"resource,omitempty"`
	Destination    Destination `json:"destination,omitempty"`
	Protocol       string      `json:"protocol,omitempty"`
	Revision       uint64      `json:"revision"`
	Deadline       time.Time   `json:"deadline"`
	LeaseExpiresAt time.Time   `json:"lease_expires_at,omitempty"`
}

type AuthenticateFunc func(context.Context, Hello) (Principal, error)
type AuthorizeOpenFunc func(context.Context, Principal, OpenRequest) (OpenClaims, error)

// Config zero values use conservative defaults. AuthorizeOpen must be supplied
// on a session that accepts streams; absent authorization always rejects OPEN.
// Contexts passed to callbacks must be honored by their implementation.
type Config struct {
	SessionTTL       time.Duration
	HandshakeTimeout time.Duration
	OpenTimeout      time.Duration
	MaxStreams       int
	MaxMetadataBytes int
	// MaxLeaseDuration caps each renewable lease, including updates from Edge.
	// Only the server side may renew; the default ceiling is one minute.
	MaxLeaseDuration time.Duration
	// MaxClockSkew widens the ceiling for leases stamped by the peer's clock.
	// It never extends a lease this side issues. The default is 30 seconds.
	MaxClockSkew time.Duration
	// MaxFlows bounds the replay ledger of active and recently closed flow IDs.
	MaxFlows int
	// FlowTombstoneTTL is how long a closed or cancelled flow ID stays in the
	// replay ledger. It must outlive any delayed OPEN or control message.
	FlowTombstoneTTL time.Duration
	AuthorizeOpen    AuthorizeOpenFunc
}

var (
	ErrAuthentication = errors.New("session authentication rejected")
	ErrProtocol       = errors.New("invalid agents protocol")
	ErrUnauthorized   = errors.New("stream authorization rejected")
	ErrRole           = errors.New("stream direction or purpose is not permitted")
	ErrExpired        = errors.New("session or stream expired")
	ErrMetadataLimit  = errors.New("metadata exceeds size limit")
	ErrStreamLimit    = errors.New("session stream limit reached")
	ErrClosed         = errors.New("session closed")
	ErrDuplicateFlow  = errors.New("flow ID already used in session")
)
